export const resources = { tr: { translation: tr }, en: { translation: en } } as const;
// i18next replaces the bundles inside `resources` when the organization's texts are applied; this copy keeps the
// built-in texts for fields the admin leaves empty
export const builtInBundles: { tr: Resources; en: Resources } = JSON.parse(JSON.stringify({ tr, en }));

const LANGUAGE_KEY = "olr.language";

function storedLanguage(): "tr" | "en" | null {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (stored === "tr" || stored === "en") return stored;
  } catch {
    // Storage blocked: fall back to the default
  }
  return null;
}

/** The user picked a language on this browser; the organization's default language then does not apply. */
export function hasStoredLanguage() {
  return storedLanguage() !== null;
}

export function setLanguage(language: "tr" | "en") {
  void i18n.changeLanguage(language);
  document.documentElement.lang = language;
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // The choice then lasts for this page view only
  }
}

void i18n.use(initReactI18next).init({
  resources,
  lng: storedLanguage() ?? "tr",
  fallbackLng: "tr",
  interpolation: { escapeValue: false },
  returnObjects: true,
  showSupportNotice: false,
  // Texts set by the organization replace the built-in bundles at runtime (src/lib/uiSettings.ts)
  react: { bindI18nStore: "added" },
});

export default i18n;
