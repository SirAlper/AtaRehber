export const resources = { tr: { translation: tr }, en: { translation: en } } as const;

const LANGUAGE_KEY = "olr.language";

function initialLanguage(): "tr" | "en" {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (stored === "tr" || stored === "en") return stored;
  } catch {
    // Storage blocked: fall back to the default
  }
  return "tr";
}

export function setLanguage(language: "tr" | "en") {
  void i18n.changeLanguage(language);
  document.documentElement.lang = language;
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // The choice then lasts for this page view only
  }
}

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage(),
  fallbackLng: "tr",
  interpolation: { escapeValue: false },
  returnObjects: true,
  showSupportNotice: false,
});

export default i18n;
